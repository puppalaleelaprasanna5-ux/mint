export function ChangeText({
  change,
  changePercent,
  currency,
  showAbsolute = true,
  className = "",
}: {
  change: number | null;
  changePercent: number | null;
  currency: string;
  showAbsolute?: boolean;
  className?: string;
}) {
  if (changePercent == null) return <span className={`text-subtle ${className}`}>—</span>;
  const trend = trendOf(changePercent);
  const color = trend === "up" ? "text-up" : trend === "down" ? "text-down" : "text-muted";
  const Icon = trend === "up" ? ArrowUpRight : trend === "down" ? ArrowDownRight : Minus;
  return (
    <span className={`inline-flex items-center gap-1 tabular-nums ${color} ${className}`}>
      <Icon className="size-3.5" aria-hidden />
      {showAbsolute && change != null ? <span>{formatSignedNumber(change, currency)}</span> : null}
      <span>({formatPercent(changePercent)})</span>
    </span>
  );
}

