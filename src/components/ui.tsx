/** Data freshness line: source, latest session date, and simulated/real label. */
export function Freshness({ provenance, className = "" }: { provenance: DataProvenance | null; className?: string }) {
  if (!provenance) return <span className={`text-xs text-subtle ${className}`}>No price data</span>;
  return (
    <span className={`inline-flex flex-wrap items-center gap-1.5 text-xs text-subtle ${className}`}>
      {provenance.isSimulated ? <SimulatedBadge /> : null}
      <span>
        Daily close · {formatTradingDate(provenance.asOfTradingDate)}
        {provenance.isSimulated ? "" : ` · ${sourceLabel(provenance.source)}`}
      </span>
    </span>
  );
}

